def test_crossing_is_the_existing_rule_on_warped_records(R):
    for delta in (0.0, 0.2, -0.3):
        Rw = R[:, :, M.warp_index(delta)]
        for level in (2.0, 5.0, 10.0):
            got = M.crossing_step(Rw, level)
            for c in range(8):
                for p in range(8):
                    k = P.crossing(Rw[c, p].tolist(), level)["k"]
                    assert got[c, p] == (-1 if k is None else k)
    assert (M.crossing_step(R, 10.0) == -1).sum() == 9 and (M.crossing_step(R, 5.0) == -1).sum() == 3  # the pilot's counts of 64
    assert (M.crossing_step(R, 2.0) == -1).sum() == 0


