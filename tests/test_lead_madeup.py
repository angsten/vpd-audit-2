def test_one_made_up_experiment_follows_the_seven_steps(R, by_id):
    scn = by_id["P5"]
    pop = M.population(R, scn)
    rng = rng_for(1, 0, 4, 0)
    s = M.draw_searches(rng, R, scn, "as_committed")  # the specification's step 5: the type's factor times the noise
    assert s["types_A"].shape == s["types_H"].shape == (16,) and s["delta"].shape == (5,)
    for starts in (s["starts_A"], s["starts_H"]):
        assert starts.shape == (16, 5) and all(len(set(row)) == 5 for row in starts.tolist())  # 5 distinct pilot starts per batch
    for i in (0, 7, 15):
        for k in range(5):  # every search under start k is read through that start's warped record, on both sides
            assert np.array_equal(s["rec_A"][i, k], R[s["types_A"][i], s["starts_A"][i, k], M.warp_index(float(s["delta"][k]))])
            assert np.array_equal(s["rec_H"][i, k], R[s["types_H"][i], s["starts_H"][i, k], M.warp_index(float(s["delta"][k]))])
    f = M.type_factor(R, scn.type_weight)
    assert np.all(np.abs(s["v"] / f[s["types_H"]] - 1) < 0.6)  # vulnerability: the type's factor times a log-normal near 1
    a = M.row_cells(rng, scn, pop["n80"], s, "n80")
    assert a["attack_present"].all() and a["heldout_present"].all()
    assert np.array_equal(a["own"], s["rec_H"][:, :, 80]) and np.array_equal(a["own20"], s["rec_H"][:, :, 20])
    assert np.array_equal(a["start"], s["rec_H"][:, :, 0]) and np.array_equal(a["attack_own"], s["rec_A"][:, :, 80])
    # carried = start + v * e * rho * (the attack setting's own added harm); shuffled = S_0 * v * u
    e = (a["carried"] - a["start"][None]) / (s["v"][None, :, None] * 0.6 * (a["attack_own"] - a["attack_start"])[:, None, :])
    u = a["shuffled_mean"] / (0.40 * s["v"][None, :, None])
    assert e.mean() == pytest.approx(1.0, abs=0.03) and e.std() == pytest.approx(0.2, rel=0.1)
    assert u.mean() == pytest.approx(1.0, abs=0.01) and u.std() == pytest.approx(0.05, rel=0.1)
    # at a harm level: the first step whose two-step mean reaches it, the harm of that setting, and missing searches
    h = M.row_cells(rng, scn, pop["h10"], s, "h10")
    step = M.crossing_step(s["rec_H"], 10.0)
    assert np.array_equal(h["heldout_present"], step != -1)
    j, k = np.argwhere(step != -1)[0]
    assert h["own"][j, k] == s["rec_H"][j, k, step[j, k]] and np.isnan(h["own"][step == -1]).all()
    there = np.broadcast_to(h["attack_present"][:, None, :], h["carried"].shape)
    assert np.isnan(h["carried"][~there]).all() and not np.isnan(h["carried"][there]).any()


def test_the_two_versions_differ_in_the_vulnerability_alone(R, by_id):
    """Amendment 2, Section 4: amended, v_j = g_j; as committed, v_j = f_c(j) g_j. Everything else is shared, on the same
    draws, and every truth is the same."""
    scn = by_id["P5"]
    pop = M.population(R, scn)
    f = M.type_factor(R, scn.type_weight)
    assert f == pytest.approx([1.00, 0.96, 0.84, 0.87, 1.99, 0.79, 0.76, 0.78], abs=0.005)  # the amendment's table
    assert np.delete(f, M.C5).mean() == pytest.approx(0.858, abs=5e-4)  # its worked example: a side with no C5 batch
    both = {}
    for version in M.VERSIONS:
        rng = rng_for(1, 0, 4, 5)
        s = M.draw_searches(rng, R, scn, version)
        both[version] = (s, M.row_cells(rng, scn, pop["n80"], s, "n80"))
    (sa, a), (sc, c) = both["amended"], both["as_committed"]
    for key in ("types_A", "types_H", "starts_A", "starts_H", "delta", "rec_A", "rec_H", "g"):
        assert np.array_equal(sa[key], sc[key]), key
    assert np.array_equal(sa["v"], sa["g"])  # log-normal noise alone, independent of the batch's type
    assert np.array_equal(sc["v"], f[sc["types_H"]] * sc["g"])
    for key in ("start", "own", "own20", "attack_start", "attack_own"):
        assert np.array_equal(a[key], c[key]), key
    ratio = f[sa["types_H"]][None, :, None]  # carried-over added harm and shuffled harm share the vulnerability
    assert (c["carried"] - c["start"][None]) == pytest.approx((a["carried"] - a["start"][None]) * ratio, rel=1e-12)
    assert c["shuffled_mean"] == pytest.approx(a["shuffled_mean"] * ratio, rel=1e-12)
    with pytest.raises(AssertionError):
        M.draw_searches(rng_for(1, 0, 4, 5), R, scn, "another")


