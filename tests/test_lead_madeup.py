def test_scenario_rules_for_retention_jumps_and_forced_missing_searches(R, by_id):
    # P13: 0.3 if the attack setting's own raw harm is under 5 nats, else 0.9
    scn = by_id["P13"]
    rng = rng_for(1, 0, 12, 1)
    s = M.draw_searches(rng, R, scn)
    a = M.row_cells(rng, scn, M.population(R, scn)["n80"], s, "n80")
    share = ((a["carried"] - a["start"][None]) / s["v"][None, :, None]).mean(axis=1) / (a["attack_own"] - a["attack_start"])
    low = a["attack_own"] < 5
    assert low.any() and (~low).any()
    assert share[low].mean() == pytest.approx(0.3, abs=0.03) and share[~low].mean() == pytest.approx(0.9, abs=0.05)
    # T3: 0.4 for settings found on type-C5 attack batches, 0.8 otherwise
    scn = by_id["T3"]
    for e in range(40):
        rng = rng_for(1, 0, 15, e)
        s = M.draw_searches(rng, R, scn)
        if (s["types_A"] == M.C5).any():
            break
    a = M.row_cells(rng, scn, M.population(R, scn)["n20"], s, "n20")
    share = ((a["carried"] - a["start"][None]) / s["v"][None, :, None]).mean(axis=1) / (a["attack_own"] - a["attack_start"])
    is_c5 = s["types_A"] == M.C5
    assert share[is_c5].mean() == pytest.approx(0.4, abs=0.05) and share[~is_c5].mean() == pytest.approx(0.8, abs=0.05)
    # T5: about 2 percent of attack searches carry 40 raw nats to every held-out batch, and 1 percent of the other cells
    scn = by_id["T5"]
    pop = M.population(R, scn)
    whole = cells = total_searches = total_cells = 0
    for e in range(60):
        rng = rng_for(1, 0, 17, e)
        s = M.draw_searches(rng, R, scn)
        a = M.row_cells(rng, scn, pop["n20"], s, "n20")
        is40 = a["carried"] == 40.0
        all40 = is40.all(axis=1)
        whole += all40.sum(); total_searches += all40.size
        cells += (is40 & ~all40[:, None, :]).sum(); total_cells += (~all40).sum() * 16
    assert whole / total_searches == pytest.approx(0.02, abs=0.008) and cells / total_cells == pytest.approx(0.01, abs=0.002)
    # T7: all 5 searches of one attack batch missing, and the 5 held-out searches with the lowest mean carried-over harm
    scn = by_id["T7"]
    pop = M.population(R, scn)
    rng = rng_for(1, 0, 26, 0)
    s = M.draw_searches(rng, R, scn)
    natural_a, natural_b = M.crossing_step(s["rec_A"], 5.0) != -1, M.crossing_step(s["rec_H"], 5.0) != -1
    a = M.row_cells(rng, scn, pop["h5"], s, "h5")
    gone = natural_a & ~a["attack_present"]
    assert (~a["attack_present"]).all(axis=1).sum() >= 1 and gone.any(axis=1).sum() <= 1  # one whole attack batch
    removed = natural_b & ~a["heldout_present"]
    assert 0 < removed.sum() <= 5 and (~a["heldout_present"]).sum() >= 5


