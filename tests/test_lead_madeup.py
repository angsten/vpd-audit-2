def test_the_multiplier_a_cell_needs_and_its_rounding():
    """Amendment 1, Section 5.3: the 95th percentile of |d| / w and, on a line, the 96.25th percentiles of d / w each way;
    rounded up to a multiple of 0.05. Its worked example: 1.12 gives 1.15."""
    r = np.linspace(-2.0, 2.0, 4001)
    w = np.full(r.size, 0.3)
    assert M.multiplier_needed(r * w, w, on_line=False) == pytest.approx(np.percentile(np.abs(r), 95), rel=1e-12) == pytest.approx(1.9, abs=1e-9)
    skew = np.concatenate([np.linspace(0.0, 3.0, 2001), np.linspace(-1.0, 0.0, 2001)])
    assert M.multiplier_needed(skew, np.ones(skew.size), on_line=True) == pytest.approx(np.percentile(skew, 96.25), rel=1e-12)
    assert M.multiplier_needed(skew, np.ones(skew.size), on_line=True) > M.multiplier_needed(skew, np.ones(skew.size), on_line=False)
    assert M.round_up_to_grid(1.12) == 1.15
    assert [M.round_up_to_grid(x) for x in (1.0, 1.0001, 1.05, 1.15, 1.1500001, 1.449, 1.5, 1.51)] == [1.0, 1.05, 1.05, 1.15, 1.2, 1.45, 1.5, 1.55]


class ScriptedTest:
    """Stands in for the samples: judges every cell from a script of coverage by (seed, row, multiplier)."""

    def __init__(self, coverage) -> None:
        self.coverage, self.calls = coverage, []

    def judge_cells(self, seed_no, cells, multiplier=None):
        self.calls.append((seed_no, sorted({row for _, row, _ in cells}), dict(multiplier or {})))
        out = []
        for scn, row, stat in cells:
            lam = (multiplier or {}).get(row, 1.0)
            c = self.coverage(seed_no, scn, row, stat, lam)
            out.append({"scenario": scn, "row": row, "statistic": stat, "coverage": c, "above": 0.0, "below": 1 - c, "rerun": c < 0.935,
                        "judged_on": 10_000 if c < 0.935 else 2_000, "fail": c < 0.925, "multiplier_needed": 1.0})
        return out


def _first_cells(needed: dict[str, float], failing: set[str]) -> list[dict]:
    cells = []
    for row in M.ALL_ROWS:
        for scn in ("P1", "P2"):
            worst = scn == "P1" and row in failing
            cells.append({"scenario": scn, "row": row, "statistic": "carries", "coverage": 0.918 if worst else 0.95, "above": 0.0, "below": 0.0,
                          "fail": worst, "multiplier_needed": needed.get(row, 0.98) if scn == "P1" else 0.9})
    return cells


def test_the_repair_is_computed_not_chosen():
    # the amendment's worked example: the worst cell needs 1.12, no other needs more; the row's multiplier is 1.15, and
    # if the fresh set passes, the row is done
    test = ScriptedTest(lambda seed, scn, row, stat, lam: 0.951)
    rows = M.repair(test, _first_cells({"n40": 1.12}, {"n40"}))
    assert rows["n40"]["multiplier"] == 1.15 and rows["n40"]["failed_cells"] == ["P1 carries"] and not rows["n40"]["to_pi"]
    assert [(c["seed"], c["multiplier"], c["passed"]) for c in rows["n40"]["confirmation"]] == [(2, 1.15, True)]
    assert all(rows[row]["multiplier"] == 1.0 and rows[row]["confirmation"] == [] for row in M.ALL_ROWS if row != "n40")  # passing rows keep 1
    # a cell that still fails raises the multiplier by 0.05 on a fresh seed each time
    test = ScriptedTest(lambda seed, scn, row, stat, lam: 0.95 if lam >= 1.3 - 1e-9 or scn != "P1" else 0.91)
    rows = M.repair(test, _first_cells({"n80": 1.17}, {"n80"}))
    assert rows["n80"]["multiplier"] == 1.3
    assert [(c["seed"], c["multiplier"], c["passed"]) for c in rows["n80"]["confirmation"]] == [(2, 1.2, False), (3, 1.25, False), (4, 1.3, True)]
    assert rows["n80"]["confirmation"][0]["failed_cells"] == ["P1 carries"]
    # a row needing more than 1.5 goes to the PI
    rows = M.repair(ScriptedTest(lambda *a: 0.90), _first_cells({"h10": 1.44}, {"h10"}))
    assert rows["h10"]["to_pi"] and [c["multiplier"] for c in rows["h10"]["confirmation"]] == [1.45, 1.5]
    rows = M.repair(ScriptedTest(lambda *a: 0.99), _first_cells({"h10": 1.62}, {"h10"}))
    assert rows["h10"]["to_pi"] and rows["h10"]["confirmation"] == [] and rows["h10"]["largest_needed"] == 1.62
    # the largest need over all the row's core cells sets the multiplier, not the failing cell's alone
    cells = _first_cells({"n20": 1.07}, {"n20"})
    next(c for c in cells if c["row"] == "n20" and c["scenario"] == "P2")["multiplier_needed"] = 1.21
    assert M.repair(ScriptedTest(lambda *a: 0.95), cells)["n20"]["multiplier"] == 1.25


def test_a_cell_is_judged_on_its_rerun_alone_by_both_criteria():
    """Plan 1, Section 12.2: a rerun cell is judged on its 10,000; the multiplier it needs comes from that sample."""
    test = M.Test.__new__(M.Test)
    test.scenarios = {s.id: s for s in M.scenarios()}
    test.population = {"P1": {"n40": {"truth": {"carries": 0.2}}}}
    rng = np.random.default_rng(3)

    def sample(n, sd):  # estimates around the truth with half-width 1.96: coverage 95 percent at sd 1
        vals = np.full((n, 9, 8), np.nan)
        vals[:, M.S["carries"], M.F["est"]] = 0.2 + sd * rng.standard_normal(n)
        vals[:, M.S["carries"], M.F["hw"]] = 1.96
        return M.RowSample(vals=vals, generated=n, read=n, mean_missing=(0.0, 0.0), experiments=np.arange(n), vals_all=vals)

    test.samples = {(1, 0, "P1"): {"n40": sample(2_000, 1.25)}, (1, 1, "P1"): {"n40": sample(10_000, 1.0)}}
    test.sample = lambda seed, phase, scn, rows=None: test.samples[(seed, phase, scn)]
    cell = test.judged(1, "P1", "n40", "carries")
    assert cell["first"]["coverage"] < 0.9 and cell["rerun"] and cell["judged_on"] == 10_000
    assert cell["coverage"] == pytest.approx(0.95, abs=0.01) and not cell["fail"]  # the 2,000 no longer count
    assert cell["multiplier_needed"] == pytest.approx(1.0, abs=0.05) and cell["line"] == 0.2
    widened = test.judged(1, "P1", "n40", "carries", multiplier=1.5)
    assert widened["first"]["coverage"] > 0.96 and not widened["rerun"] and widened["judged_on"] == 2_000
    assert "all_experiments" not in cell  # a search-length row is read in every experiment
    # at a harm level, beside the judgement and as description: every experiment of the same sample, read or not
    test.population["P1"]["h10"] = {"truth": {"carries": 0.2}}
    read, everything = sample(2_000, 1.0), sample(2_000, 3.0)
    read.vals_all, read.generated = everything.vals, 8_000
    test.samples[(1, 0, "P1")]["h10"] = read
    level = test.judged(1, "P1", "h10", "carries")
    assert not level["rerun"] and level["coverage"] == pytest.approx(0.95, abs=0.015) and level["share_read"] == 0.25
    assert level["all_experiments"]["n"] == 2_000 and level["all_experiments"]["coverage"] == pytest.approx(0.486, abs=0.03)
    assert not level["fail"]  # the criterion is the first judgement; the second changes nothing


