def test_the_truth_at_a_harm_level_is_the_expected_total_over_the_expected_count(R, by_id):
    """The erratum, item 2, by plain loops: at each point of the grid of start shifts, the share of searches present and
    their totals; the yardstick weighted by the share present."""
    scn = by_id["P8"]  # "large" with its truth at zero, start effect 0.09
    level, sigma = 10.0, 0.09
    grid = np.linspace(-4 * sigma, 4 * sigma, 401)
    dens = np.exp(-0.5 * (grid / sigma) ** 2)
    count = tot_Y = tot_O = tot_q = 0.0
    for d, wd in zip(grid, dens):
        idx = [min(320, round(t * math.exp(d))) for t in range(321)]
        present = sum_Y = sum_O = sum_q = 0.0
        for c in range(8):
            for p in range(8):
                rec = R[c, p, idx].tolist()
                k = P.crossing(rec, level)["k"]
                sum_q += rec[20] / 64
                if k is not None:
                    present += 1 / 64
                    sum_Y += rec[k] / 64
                    sum_O += (rec[k] - rec[0]) / 64
        count += wd * present
        tot_Y += wd * sum_Y
        tot_O += wd * sum_O
        tot_q += wd * present * sum_q
    got = M.population(R, scn)["h10"]
    assert got["mu_Y"] == pytest.approx(tot_Y / count, rel=1e-10) and got["mu_O"] == pytest.approx(tot_O / count, rel=1e-10)
    assert got["mu_q"] == pytest.approx(tot_q / count, rel=1e-10)  # P8 must use that same weighted mu_q
    assert got["share_present"] == pytest.approx(count / dens.sum(), rel=1e-10)
    assert got["rho_row"] == pytest.approx((tot_q / count - got["mu_k"]) / (tot_O / count), rel=1e-10)
    # without a start effect the simple formulas are exact: the pilot's 9 of 64 searches never reach 10 nats
    flat = M.population(R, by_id["P7"])["h10"]
    assert flat["share_present"] == pytest.approx(55 / 64, abs=1e-12)


